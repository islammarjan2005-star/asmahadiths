// Helper function to find duas by keywords
export const findDuasByKeyword = (keyword) => {
  const lower = keyword.toLowerCase();
  return situationalDuas.filter(
    (dua) =>
      dua.keywords.some((k) => k.includes(lower)) ||
      dua.category.includes(lower) ||
      dua.title.toLowerCase().includes(lower) ||
      dua.translation.toLowerCase().includes(lower)
  );
};

// Helper function to get duas by category
export const getDuasByCategory = (categoryId) => {
  return situationalDuas.filter((dua) => dua.category === categoryId);
};
